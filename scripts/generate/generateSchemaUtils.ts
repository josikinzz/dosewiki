import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import {
  substanceArticleSchema,
} from "../../src/schema/substance.schema";
import {
  extractFieldPaths,
  FIELD_REGISTRY_SECTION_ORDER,
  generateArticleDefaults,
  inferFieldRegistrySection,
  type FieldRegistrySection,
  type GeneratedFieldMeta,
} from "./schemaGenerationPolicy";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT_DIR = path.join(__dirname, "../../src/data/schema");

function generateDefaultsFile(): string {
  const defaults = generateArticleDefaults(substanceArticleSchema);
  const json = JSON.stringify(defaults, null, 2);

  return `/**
 * AUTO-GENERATED FILE - DO NOT EDIT DIRECTLY
 * Generated by: npm run generate:schema
 * Source: src/schema/substance.schema.ts
 */

import type { SubstanceArticle } from "../../schema";

/**
 * Create an empty SubstanceArticle with default values derived from the Zod schema.
 */
export function createEmptyArticle(): SubstanceArticle {
  return ${json.replace(/"([^"]+)":/g, "$1:")};
}
`;
}

function formatGeneratedFieldEntry(field: GeneratedFieldMeta): string {
  const defaultStr =
    field.default === null
      ? "null"
      : field.default === ""
        ? '""'
        : JSON.stringify(field.default);

  return `  "${field.path}": {
    path: "${field.path}",
    type: "${field.type}",
    default: ${defaultStr},
    isNullable: ${field.isNullable},
  }`;
}

function generateFieldRegistryShardFile(section: FieldRegistrySection, fields: GeneratedFieldMeta[]): string {
  const entries = fields.map(formatGeneratedFieldEntry).join(",\n");

  return `/**
 * AUTO-GENERATED FILE - DO NOT EDIT DIRECTLY
 * Generated by: npm run generate:schema
 * Source: src/schema/substance.schema.ts
 *
 * Generated field registry shard for the ${section} section.
 */

export const ${section}GeneratedFieldRegistry = {
${entries}
};
`;
}

function generateFieldRegistryFile(): string {
  const fields = extractFieldPaths(substanceArticleSchema);
  const sectionImports = FIELD_REGISTRY_SECTION_ORDER.filter((section) =>
    fields.some((field) => inferFieldRegistrySection(field.path) === section),
  );

  return `/**
 * AUTO-GENERATED FILE - DO NOT EDIT DIRECTLY
 * Generated by: npm run generate:schema
 * Source: src/schema/substance.schema.ts
 *
 * This barrel composes generated field-registry shards by domain.
 * Manual overrides (labels, sections, transformers) are defined in fieldOverrides.ts
 */

${sectionImports
  .map(
    (section) =>
      `import { ${section}GeneratedFieldRegistry } from "./fieldRegistry.generated/${section}";`,
  )
  .join("\n")}

export interface GeneratedFieldMeta {
  path: string;
  type: string;
  default: unknown;
  isNullable: boolean;
}

export const GENERATED_FIELD_REGISTRY: Record<string, GeneratedFieldMeta> = {
${sectionImports.map((section) => `  ...${section}GeneratedFieldRegistry,`).join("\n")}
};

/**
 * List of all field paths in the schema
 */
export const FIELD_PATHS = Object.keys(GENERATED_FIELD_REGISTRY);

export type FieldPath = (typeof FIELD_PATHS)[number];
`;
}

const SHARD_DIR = "fieldRegistry.generated";
const FIXED_OUTPUTS = ["defaults.generated.ts", "fieldRegistry.generated.ts"];

function renderOutputs(): Map<string, string> {
  const outputs = new Map<string, string>();
  outputs.set("defaults.generated.ts", generateDefaultsFile());

  const fields = extractFieldPaths(substanceArticleSchema);
  for (const section of FIELD_REGISTRY_SECTION_ORDER) {
    const sectionFields = fields.filter((field) => inferFieldRegistrySection(field.path) === section);
    if (sectionFields.length > 0) {
      outputs.set(`${SHARD_DIR}/${section}.ts`, generateFieldRegistryShardFile(section, sectionFields));
    }
  }

  outputs.set("fieldRegistry.generated.ts", generateFieldRegistryFile());
  return outputs;
}

function listCheckedInOutputs(): string[] {
  const shardDir = path.join(OUTPUT_DIR, SHARD_DIR);
  const shards = fs.existsSync(shardDir) ? fs.readdirSync(shardDir).map((name) => `${SHARD_DIR}/${name}`) : [];
  return [...FIXED_OUTPUTS.filter((file) => fs.existsSync(path.join(OUTPUT_DIR, file))), ...shards];
}

function checkOutputs(outputs: Map<string, string>): void {
  const drifted = [...outputs]
    .filter(([file, content]) => {
      const target = path.join(OUTPUT_DIR, file);
      return !fs.existsSync(target) || fs.readFileSync(target, "utf-8") !== content;
    })
    .map(([file]) => file);
  const unexpected = listCheckedInOutputs().filter((file) => !outputs.has(file));

  for (const file of drifted) console.error(`Out of date: src/data/schema/${file}`);
  for (const file of unexpected) console.error(`Not produced by the generator: src/data/schema/${file}`);

  if (drifted.length > 0 || unexpected.length > 0) {
    console.error("\nSchema helpers drifted from src/schema/substance.schema.ts. Run: bun run generate:schema");
    process.exitCode = 1;
    return;
  }
  console.log(`Schema helpers are current (${outputs.size} files).`);
}

function writeOutputs(outputs: Map<string, string>): void {
  const shardDir = path.join(OUTPUT_DIR, SHARD_DIR);
  fs.rmSync(shardDir, { recursive: true, force: true });
  fs.mkdirSync(shardDir, { recursive: true });
  for (const [file, content] of outputs) {
    fs.writeFileSync(path.join(OUTPUT_DIR, file), content, "utf-8");
    console.log(`✓ Generated: src/data/schema/${file}`);
  }
}

function main() {
  const args = process.argv.slice(2);
  const unknown = args.filter((arg) => arg !== "--check");
  if (unknown.length > 0) {
    console.error(`Unknown argument: ${unknown.join(" ")}. Usage: generateSchemaUtils.ts [--check]`);
    process.exitCode = 1;
    return;
  }

  const outputs = renderOutputs();
  if (args.includes("--check")) {
    checkOutputs(outputs);
  } else {
    writeOutputs(outputs);
  }
}

main();
