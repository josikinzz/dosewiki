// Package scripts may also expose bounded repair or migration tools. Stability is
// an explicit allowlist; the `citations:` prefix alone does not make a command stable.
export const stableCitationWorkflowCommandNames = Object.freeze([
  'citations:formal',
  'citations:apply-workbench',
  'citations:campaign',
  'citations:run-local-campaign',
  'citations:review-dossier',
  'citations:plan-second-pass',
  'citations:audit-second-pass-campaign',
  'citations:export-workbench-task',
  'citations:rebase-workbench',
  'citations:archive-production-dataset',
  'citations:audit-subsections',
  'citations:seed-subsection-tracker',
  'citations:update-subsection-status',
]);

export function buildCitationWorkflowCommands({
  command,
  workflowAccessTargets,
  workflowDryRunPolicies,
  workflowDataOpsContextPolicies,
  workflowDataUrlPolicies,
}) {
  return [
    command({
      name: 'citations:formal',
      purpose: 'Generate formal claim-level citation drafts and optionally write reviewed citation evidence.',
      env: [
        'OPENROUTER_API_KEY',
        'DATA_ADMIN_TOKEN_CITATION_EVIDENCE_REVIEW or DATA_ADMIN_KEY',
        'DATA_ADMIN_TOKEN_CITATION_EVIDENCE_WRITE or DATA_ADMIN_KEY when writing',
        'DATA_BACKEND=postgres',
        '--source-url or SOURCE_POSTGRES_URL (otherwise the selected Postgres target)',
        'TARGET_POSTGRES_URL or --target when writing',
        '--allow-remote and POSTGRES_IMPORT_CONFIRM=<hostname> for remote access',
      ],
      scriptPath: 'scripts/citations/formal-citations.mjs',
      reads: [
        workflowAccessTargets.dataSource,
        workflowAccessTargets.localExportArtifacts,
        workflowAccessTargets.openRouter,
      ],
      writes: [workflowAccessTargets.localExportArtifacts, workflowAccessTargets.dataTarget],
      dryRun: workflowDryRunPolicies.supported,
      confirmationFlag: '--confirm-citation-write',
      dataOpsContext: workflowDataOpsContextPolicies.required,
      dataUrlPolicy: workflowDataUrlPolicies.requiredSourceOptionalTarget,
    }),
    command({
      name: 'citations:apply-workbench',
      purpose: 'Adapt a reviewed workbench citation draft and optionally write it through the citation evidence path.',
      env: [
        'DATA_ADMIN_TOKEN_CITATION_EVIDENCE_WRITE or DATA_ADMIN_KEY when writing',
        'DATA_BACKEND=postgres',
        'TARGET_POSTGRES_URL or --target (required for dry-run and write; no default fallback)',
        '--expected-deployment=<host/database> matching the target',
        '--allow-remote and POSTGRES_IMPORT_CONFIRM=<hostname> for remote access',
      ],
      scriptPath: 'scripts/citations/apply-workbench-draft.mjs',
      reads: [workflowAccessTargets.localArtifacts, workflowAccessTargets.dataTarget],
      writes: [workflowAccessTargets.dataTarget],
      dryRun: workflowDryRunPolicies.supported,
      confirmationFlag: '--confirm-citation-write',
      dataOpsContext: workflowDataOpsContextPolicies.required,
      dataUrlPolicy: workflowDataUrlPolicies.requiredTarget,
    }),
    command({
      name: 'citations:campaign',
      purpose: 'Create one locked local citation campaign manifest and report immutable Pi workbench run status without generation or publication.',
      env: ['DOSEWIKI_CITATION_WORKBENCH optional'],
      scriptPath: 'tools/pi-citation-workflow/citation-campaign.mjs',
      reads: [workflowAccessTargets.localArtifacts],
      writes: [workflowAccessTargets.localArtifacts],
      dryRun: workflowDryRunPolicies.reportOnly,
      dataOpsContext: workflowDataOpsContextPolicies.notApplicable,
      dataUrlPolicy: workflowDataUrlPolicies.none,
    }),
    command({
      name: 'citations:run-local-campaign',
      purpose: 'Run or resume a sequential local-only subsection campaign from manifest state without any production apply capability.',
      env: ['DOSEWIKI_CITATION_WORKBENCH optional', 'DATA_BACKEND=postgres', 'explicit --source-url for read-only task export', '--allow-remote and POSTGRES_IMPORT_CONFIRM=<hostname> for remote access'],
      scriptPath: 'scripts/citations/local-subsection-campaign.mjs',
      reads: [workflowAccessTargets.localArtifacts, workflowAccessTargets.dataSource],
      writes: [workflowAccessTargets.localArtifacts],
      dryRun: workflowDryRunPolicies.supported,
      dataOpsContext: workflowDataOpsContextPolicies.required,
      dataUrlPolicy: workflowDataUrlPolicies.requiredSource,
    }),
    command({
      name: 'citations:review-dossier',
      purpose: 'Generate a self-contained offline review dossier from tracker-bound finalized local citation runs.',
      env: ['DOSEWIKI_CITATION_WORKBENCH optional'],
      scriptPath: 'scripts/citations/build-citation-review-dossier.mjs',
      reads: [workflowAccessTargets.localArtifacts],
      writes: [workflowAccessTargets.localExportArtifacts],
      dryRun: workflowDryRunPolicies.reviewArtifacts,
      dataOpsContext: workflowDataOpsContextPolicies.required,
      dataUrlPolicy: workflowDataUrlPolicies.none,
    }),
    command({
      name: 'citations:plan-second-pass',
      purpose: 'Score all viable uncited public subsections and write an immutable second-pass research plan without researching or publishing.',
      env: [],
      scriptPath: 'scripts/citations/plan-second-pass-research.mjs',
      reads: [workflowAccessTargets.localArtifacts],
      writes: [workflowAccessTargets.localExportArtifacts],
      dryRun: workflowDryRunPolicies.supported,
      dataOpsContext: workflowDataOpsContextPolicies.required,
      dataUrlPolicy: workflowDataUrlPolicies.none,
    }),
    command({
      name: 'citations:audit-second-pass-campaign',
      purpose: 'Fail closed unless every planned second-pass row is finalized locally or explicitly deferred, with no production writes.',
      env: ['DOSEWIKI_CITATION_WORKBENCH optional'],
      scriptPath: 'scripts/citations/audit-second-pass-campaign.mjs',
      reads: [workflowAccessTargets.localArtifacts],
      writes: [workflowAccessTargets.localExportArtifacts],
      dryRun: workflowDryRunPolicies.reviewArtifacts,
      dataOpsContext: workflowDataOpsContextPolicies.required,
      dataUrlPolicy: workflowDataUrlPolicies.none,
    }),
    command({
      name: 'citations:export-workbench-task',
      purpose: 'Export the current Postgres article state into the external citation workbench task directory.',
      env: [
        'DATA_BACKEND=postgres',
        '--source-url or SOURCE_POSTGRES_URL (otherwise the selected Postgres target)',
        '--allow-remote and POSTGRES_IMPORT_CONFIRM=<hostname> for remote access',
      ],
      scriptPath: 'scripts/citations/export-workbench-task-from-data.mjs',
      reads: [workflowAccessTargets.dataSource],
      writes: [workflowAccessTargets.localExportArtifacts],
      dryRun: workflowDryRunPolicies.supported,
      dataOpsContext: workflowDataOpsContextPolicies.required,
      dataUrlPolicy: workflowDataUrlPolicies.requiredSource,
    }),
    command({
      name: 'citations:rebase-workbench',
      purpose: 'Rebase a local citation workbench draft onto current exported article state without publishing it.',
      env: [
        'DATA_BACKEND=postgres',
        '--source-url or SOURCE_POSTGRES_URL (otherwise the selected Postgres target)',
        '--allow-remote and POSTGRES_IMPORT_CONFIRM=<hostname> for remote access',
        'DOSEWIKI_CITATION_WORKBENCH optional',
      ],
      scriptPath: 'scripts/citations/rebase-workbench-draft.mjs',
      reads: [workflowAccessTargets.localArtifacts, workflowAccessTargets.dataSource],
      writes: [workflowAccessTargets.localArtifacts],
      dryRun: workflowDryRunPolicies.none,
      dataOpsContext: workflowDataOpsContextPolicies.required,
      dataUrlPolicy: workflowDataUrlPolicies.requiredSource,
    }),
    command({
      name: 'citations:archive-production-dataset',
      purpose: 'Archive the current production/public Postgres substance dataset before citation rollout writes.',
      env: ['DATA_BACKEND=postgres', '--source-url or SOURCE_POSTGRES_URL (otherwise the selected Postgres target)', '--allow-remote and POSTGRES_IMPORT_CONFIRM=<hostname> for remote access'],
      scriptPath: 'scripts/citations/archive-production-dataset.mjs',
      reads: [workflowAccessTargets.dataSource],
      writes: [workflowAccessTargets.localArtifacts],
      dryRun: workflowDryRunPolicies.none,
      dataOpsContext: workflowDataOpsContextPolicies.required,
      dataUrlPolicy: workflowDataUrlPolicies.requiredSource,
    }),
    command({
      name: 'citations:audit-subsections',
      purpose: 'Refresh the read-only public-only subsection citation audit from live production across all six citable sections.',
      env: [
        'DATA_BACKEND=postgres',
        '--source-url or SOURCE_POSTGRES_URL (otherwise the selected Postgres target)',
        '--allow-remote and POSTGRES_IMPORT_CONFIRM=<hostname> for remote access',
        'DATA_ADMIN_KEY optional, enables citationEvidence status counts',
      ],
      scriptPath: 'scripts/citations/audit-subsection-citations.mjs',
      reads: [workflowAccessTargets.dataSource, workflowAccessTargets.localArtifacts],
      writes: [workflowAccessTargets.localArtifacts],
      dryRun: workflowDryRunPolicies.none,
      dataOpsContext: workflowDataOpsContextPolicies.required,
      dataUrlPolicy: workflowDataUrlPolicies.requiredSource,
    }),
    command({
      name: 'citations:seed-subsection-tracker',
      purpose: 'Seed or merge the subsection rollout tracker from the refreshed audit ledger without touching the slug-level queue.',
      env: ['DOSEWIKI_CITATION_WORKBENCH optional'],
      scriptPath: 'scripts/citations/seed-subsection-rollout-tracker.mjs',
      reads: [workflowAccessTargets.localArtifacts],
      writes: [workflowAccessTargets.localArtifacts],
      dryRun: workflowDryRunPolicies.supported,
      dataOpsContext: workflowDataOpsContextPolicies.required,
      dataUrlPolicy: workflowDataUrlPolicies.none,
    }),
    command({
      name: 'citations:update-subsection-status',
      purpose: 'Transition a slug+section row in the subsection rollout tracker with an auditable timestamp.',
      env: ['DOSEWIKI_CITATION_WORKBENCH optional'],
      scriptPath: 'scripts/citations/update-subsection-rollout-status.mjs',
      reads: [workflowAccessTargets.localArtifacts],
      writes: [workflowAccessTargets.localArtifacts],
      dryRun: workflowDryRunPolicies.supported,
      dataOpsContext: workflowDataOpsContextPolicies.required,
      dataUrlPolicy: workflowDataUrlPolicies.none,
    }),
  ];
}
