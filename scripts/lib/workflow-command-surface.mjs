export const workflowDryRunPolicies = Object.freeze({
  none: 'none',
  readOnly: 'read-only',
  reportOnly: 'report-only',
  supported: 'supported',
  reviewArtifacts: 'review-artifacts',
});

export const workflowDataOpsContextPolicies = Object.freeze({
  required: 'required',
  notApplicable: 'not-applicable',
  batchDeferred: 'batch-deferred',
});

export const workflowDataUrlPolicies = Object.freeze({
  none: 'none',
  optionalSource: 'optional-source',
  requiredSource: 'required-source',
  requiredSourceOptionalTarget: 'required-source-optional-target',
  optionalTarget: 'optional-target',
  requiredTarget: 'required-target',
  sourceAndTarget: 'source-and-target',
});

function command({
  name,
  purpose,
  env = [],
  scriptPath,
  reads = [],
  writes = [],
  dryRun,
  confirmationFlag = null,
  dataOpsContext = workflowDataOpsContextPolicies.notApplicable,
  dataUrlPolicy = workflowDataUrlPolicies.none,
}) {
  return {
    name,
    purpose,
    env,
    policy: {
      scriptPath,
      reads,
      writes,
      dryRun,
      confirmationFlag,
      dataOpsContext,
      dataUrlPolicy,
      productionWriteBoundary: writes.includes('data-target')
        ? 'explicit-target-ceremony'
        : null,
    },
  };
}

